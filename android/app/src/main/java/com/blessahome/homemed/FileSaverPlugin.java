package com.blessahome.homemed;

import android.Manifest;
import android.app.NotificationChannel;
import android.app.NotificationManager;
import android.app.PendingIntent;
import android.content.ContentResolver;
import android.content.ContentValues;
import android.content.Context;
import android.content.Intent;
import android.content.pm.PackageManager;
import android.net.Uri;
import android.os.Build;
import android.os.Environment;
import android.provider.MediaStore;
import android.util.Base64;

import androidx.core.app.NotificationCompat;
import androidx.core.app.NotificationManagerCompat;
import androidx.core.content.ContextCompat;
import androidx.core.content.FileProvider;

import com.getcapacitor.JSObject;
import com.getcapacitor.Plugin;
import com.getcapacitor.PluginCall;
import com.getcapacitor.PluginMethod;
import com.getcapacitor.annotation.CapacitorPlugin;

import java.io.File;
import java.io.FileOutputStream;
import java.io.OutputStream;

/**
 * Saves a file generated by the web app (PDF / XLSX / CSV) into the device's
 * Downloads folder and posts a notification that opens it when tapped.
 * The WebView alone cannot do this: blob downloads give no feedback and the
 * user never learns where the file went.
 */
@CapacitorPlugin(name = "FileSaver")
public class FileSaverPlugin extends Plugin {
    private static final String CHANNEL_ID = "arquivos";
    private static final int NOTIFICATION_ID_BASE = 7000;

    /** saveAndNotify({ filename, mimeType, base64 }) -> { uri, notified } */
    @PluginMethod
    public void saveAndNotify(PluginCall call) {
        String filename = call.getString("filename");
        String mimeType = call.getString("mimeType", "application/octet-stream");
        String base64 = call.getString("base64");
        if (filename == null || filename.isEmpty() || base64 == null) {
            call.reject("filename e base64 são obrigatórios");
            return;
        }
        // Never let the web side choose a path.
        filename = filename.replaceAll("[\\\\/:*?\"<>|]", "_");

        try {
            byte[] bytes = Base64.decode(base64, Base64.DEFAULT);
            Uri uri = save(filename, mimeType, bytes);
            boolean notified = notifySaved(filename, mimeType, uri);
            JSObject ret = new JSObject();
            ret.put("uri", uri.toString());
            ret.put("notified", notified);
            call.resolve(ret);
        } catch (Exception e) {
            call.reject("Não foi possível salvar o arquivo: " + e.getMessage());
        }
    }

    /** openFile({ uri, mimeType }) opens a file saved earlier (used when notifications are blocked). */
    @PluginMethod
    public void openFile(PluginCall call) {
        String uri = call.getString("uri");
        String mimeType = call.getString("mimeType", "*/*");
        if (uri == null) {
            call.reject("uri é obrigatório");
            return;
        }
        try {
            Intent intent = viewIntent(Uri.parse(uri), mimeType);
            intent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
            getContext().startActivity(intent);
            call.resolve();
        } catch (Exception e) {
            call.reject("Nenhum aplicativo encontrado para abrir este arquivo");
        }
    }

    private Uri save(String filename, String mimeType, byte[] bytes) throws Exception {
        Context ctx = getContext();
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
            ContentResolver resolver = ctx.getContentResolver();
            ContentValues values = new ContentValues();
            values.put(MediaStore.MediaColumns.DISPLAY_NAME, filename);
            values.put(MediaStore.MediaColumns.MIME_TYPE, mimeType);
            values.put(MediaStore.MediaColumns.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS);
            Uri uri = resolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, values);
            if (uri == null) throw new Exception("MediaStore recusou o arquivo");
            try (OutputStream out = resolver.openOutputStream(uri)) {
                if (out == null) throw new Exception("sem saída de gravação");
                out.write(bytes);
            }
            return uri;
        }
        // Android 7-9: app-specific Downloads folder (no storage permission needed).
        File dir = ctx.getExternalFilesDir(Environment.DIRECTORY_DOWNLOADS);
        if (dir == null) dir = ctx.getFilesDir();
        if (!dir.exists()) dir.mkdirs();
        File file = new File(dir, filename);
        try (FileOutputStream out = new FileOutputStream(file)) {
            out.write(bytes);
        }
        return FileProvider.getUriForFile(ctx, ctx.getPackageName() + ".fileprovider", file);
    }

    private Intent viewIntent(Uri uri, String mimeType) {
        Intent intent = new Intent(Intent.ACTION_VIEW);
        intent.setDataAndType(uri, mimeType);
        intent.addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION);
        return intent;
    }

    private boolean notifySaved(String filename, String mimeType, Uri uri) {
        Context ctx = getContext();
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU
                && ContextCompat.checkSelfPermission(ctx, Manifest.permission.POST_NOTIFICATIONS)
                != PackageManager.PERMISSION_GRANTED) {
            return false;
        }
        if (!NotificationManagerCompat.from(ctx).areNotificationsEnabled()) return false;

        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            NotificationChannel channel = new NotificationChannel(
                    CHANNEL_ID, "Arquivos exportados", NotificationManager.IMPORTANCE_DEFAULT);
            channel.setDescription("Avisa quando um arquivo exportado foi salvo");
            ctx.getSystemService(NotificationManager.class).createNotificationChannel(channel);
        }

        int flags = PendingIntent.FLAG_UPDATE_CURRENT;
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) flags |= PendingIntent.FLAG_IMMUTABLE;
        int id = NOTIFICATION_ID_BASE + (int) (System.currentTimeMillis() % 100000);
        PendingIntent pending = PendingIntent.getActivity(ctx, id, viewIntent(uri, mimeType), flags);

        int icon = ctx.getResources().getIdentifier("ic_stat_homemed", "drawable", ctx.getPackageName());
        if (icon == 0) icon = android.R.drawable.stat_sys_download_done;

        NotificationCompat.Builder builder = new NotificationCompat.Builder(ctx, CHANNEL_ID)
                .setSmallIcon(icon)
                .setColor(0xFF2563EB)
                .setContentTitle("Arquivo salvo em Downloads")
                .setContentText(filename + " — toque para abrir")
                .setContentIntent(pending)
                .setAutoCancel(true)
                .setPriority(NotificationCompat.PRIORITY_DEFAULT);
        try {
            NotificationManagerCompat.from(ctx).notify(id, builder.build());
            return true;
        } catch (SecurityException e) {
            return false;
        }
    }
}
